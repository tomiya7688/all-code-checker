using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace AllCodeChecker.Analysis;

internal static class CSharpGeneratedCodeDetector
{
    public static bool IsGenerated(string path, string source)
    {
        string fileName = Path.GetFileName(path);
        if (fileName.EndsWith(".g.cs", StringComparison.OrdinalIgnoreCase)
            || fileName.EndsWith(".generated.cs", StringComparison.OrdinalIgnoreCase)
            || fileName.EndsWith(".designer.cs", StringComparison.OrdinalIgnoreCase)
            || fileName.Equals("AssemblyInfo.cs", StringComparison.OrdinalIgnoreCase))
        {
            return true;
        }

        string header = source[..Math.Min(source.Length, 2048)];
        return SyntaxFactory.ParseLeadingTrivia(header).Any(trivia =>
            (trivia.IsKind(SyntaxKind.SingleLineCommentTrivia)
                || trivia.IsKind(SyntaxKind.MultiLineCommentTrivia)
                || trivia.IsKind(SyntaxKind.SingleLineDocumentationCommentTrivia)
                || trivia.IsKind(SyntaxKind.MultiLineDocumentationCommentTrivia))
            && trivia.ToFullString().Contains("<auto-generated", StringComparison.OrdinalIgnoreCase));
    }
}
